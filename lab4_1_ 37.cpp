// 1. Декларація (прототип) функції
double RectP(double x1, double y1, double x2, double y2);

int main() {
    setlocale(LC_ALL, "Ukrainian");

    // Змінні для зберігання координат протилежних вершин трьох прямокутників
    double ax1, ay1, ax2, ay2;
    double bx1, by1, bx2, by2;
    double cx1, cy1, cx2, cy2;

    // Введення даних для першого прямокутника
    cout << "Введіть координати протилежних вершин 1-го прямокутника (x1 y1 x2 y2): ";
    cin >> ax1 >> ay1 >> ax2 >> ay2;

    // Введення даних для другого прямокутника
    cout << "Введіть координати протилежних вершин 2-го прямокутника (x1 y1 x2 y2): ";
    cin >> bx1 >> by1 >> bx2 >> by2;

    // Введення даних для третього прямокутника
    cout << "Введіть координати протилежних вершин 3-го прямокутника (x1 y1 x2 y2): ";
    cin >> cx1 >> cy1 >> cx2 >> cy2;

    // 3. Виклик функції та виведення периметрів без використання циклів
    cout << "Периметр 1-го прямокутника: " << RectP(ax1, ay1, ax2, ay2) << endl;
    cout << "Периметр 2-го прямокутника: " << RectP(bx1, by1, bx2, by2) << endl;
    cout << "Периметр 3-го прямокутника: " << RectP(cx1, cy1, cx2, cy2) << endl;

    return 0;
}

// 2. Визначення функції RectP
// Обчислює ширину та висоту за модулем різниці координат і повертає периметр: 2 * (ширина + висота)
double RectP(double x1, double y1, double x2, double y2) {
    double width = fabs(x2 - x1);  // Довжина сторони вздовж осі X
    double height = fabs(y2 - y1); // Довжина сторони вздовж осі Y
    return 2 * (width + height);   // Формула периметра прямокутника
}